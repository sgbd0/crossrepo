def _clue_for(clues: dict[str, str], word: str, length: int) -> str:
    return clues.get(word) or f"An identifier from this repo ({length} letters)"


def render_text(layout: Layout, clues: dict[str, str], title: str = "",
                reveal: bool = False) -> str:
    """Plain-text puzzle: numbered blank grid plus Across/Down clues."""
    starts: dict[tuple[int, int], int] = {}
    for p in layout.placements:
        starts.setdefault((p.row, p.col), p.number)
    lines: list[str] = []
    if title:
        lines += [title, ""]
    for r in range(layout.rows):
        row = []
        for c in range(layout.cols):
            if (r, c) not in layout.cells:
                row.append("###")
            elif reveal:
                row.append(f" {layout.cells[(r, c)]} ")
            elif (r, c) in starts:
                row.append(f"{starts[(r, c)]:^3}")
            else:
                row.append(" . ")
        lines.append("".join(row))
    lines.append("")
    for direction, header in ((ACROSS, "Across"), (DOWN, "Down")):
        lines.append(header)
        ordered = sorted((p for p in layout.placements if p.direction == direction),
                         key=lambda p: p.number)
        for p in ordered:
            clue = _clue_for(clues, p.word, len(p.word))
            lines.append(f"  {p.number:3d}. {clue} [{len(p.word)}]")
        lines.append("")
    if layout.dropped:
        lines.append("Skipped (no fit): " + ", ".join(layout.dropped))
    return "\n".join(lines)


def render_json(layout: Layout, clues: dict[str, str], title: str = "",
                seed: int = 0, meta: dict | None = None) -> dict:
    """Machine-readable export for custom renderers and CI badges."""
    words = []
    for p in sorted(layout.placements, key=lambda p: (p.number, p.direction)):
        words.append({
            "answer": p.word,
            "clue": _clue_for(clues, p.word, len(p.word)),
            "number": p.number,
            "row": p.row,
            "col": p.col,
            "direction": p.direction,
            "length": len(p.word),
        })
    payload = {
        "tool": "crossrepo",
        "version": __version__,
        "title": title,
        "seed": seed,
        "size": {"rows": layout.rows, "cols": layout.cols},
        "grid": [[layout.cells.get((r, c)) for c in range(layout.cols)]
                 for r in range(layout.rows)],
        "words": words,
        "dropped": list(layout.dropped),
    }
    if meta:
        payload["stats"] = meta
    return payload


def render_html(layout: Layout, clues: dict[str, str], title: str = "CrossRepo",
                seed: int = 0) -> str:
    """One self-contained HTML file: typeable grid, check and reveal."""
    payload = {
        "rows": layout.rows,
        "cols": layout.cols,
        "seed": seed,
        "cells": {f"{r},{c}": letter for (r, c), letter in layout.cells.items()},
        "words": [
            {
                "word": p.word,
                "clue": _clue_for(clues, p.word, len(p.word)),
                "row": p.row,
                "col": p.col,
                "dir": p.direction,
                "number": p.number,
            }
            for p in layout.placements
        ],
    }
    return (_HTML_TEMPLATE
            .replace("__TITLE__", _escape(title))
            .replace("__SEED__", str(seed))
            .replace("__COUNT__", str(len(layout.placements)))
            .replace("__PAYLOAD__", json.dumps(payload, ensure_ascii=False)))


def _escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
